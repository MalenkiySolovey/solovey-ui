// Provider packaging policy and static observation. Source identities come
// from the build owner; executable/container inspection stays in internal/release.
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { resolveProviderSource } from './core-provider-build.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
export const targets = JSON.parse(fs.readFileSync(new URL('./release-targets.json', import.meta.url), 'utf8'))
export const legacySchema = 'solovey.release/v1'
export const providerSchema = 'solovey.release/v2'

export function linuxBuildTargets(schema = providerSchema) {
  if (![legacySchema, providerSchema].includes(schema)) throw Error('Unsupported release schema')
  const official = resolveProviderSource().provider
  const result = targets.linux.map(target => ({ ...target, provider: official, artifact_suffix: '' }))
  if (schema === providerSchema) {
    const policy = targets.extended
    const { provider } = resolveProviderSource({ provider: policy.provider })
    assert.notEqual(provider, official, 'Extended platform policy must select a separate build flavor')
    assert.equal(new Set(policy.linux).size, policy.linux.length, 'Duplicate Extended platform policy')
    for (const platform of policy.linux) {
      const target = targets.linux.find(item => item.platform === platform)
      assert.ok(target, 'Extended platform is outside the canonical Linux targets')
      result.push({ ...target, provider, artifact_suffix: `-${provider}` })
    }
  }
  return result
}

export function linuxPanelArtifacts(schema = providerSchema) {
  return linuxBuildTargets(schema).flatMap(({ platform, provider, artifact_suffix }) =>
    ['full', 'core'].map(profile => ({
      name: `solovey-ui${artifact_suffix}${profile === 'core' ? '-core' : ''}-linux-${platform}.tar.gz`,
      platform: 'linux', arch: platform, profile, provider, role: `panel-${profile}`,
    })))
}

export function installerProviderPolicy() {
  const cases = linuxPanelArtifacts().map(target => {
    const name = target.name.replace(/^solovey-ui/, '${APP_NAME}')
    return `        ${target.provider}/${target.arch}/${target.profile}) printf '%s\\n' "${name}" ;;`
  })
  return [
    '# BEGIN GENERATED CORE PROVIDER RELEASE POLICY',
    '# Generated by scripts/release-providers.mjs installer-policy.',
    'release_artifact_name() {',
    '    case "${CORE_PROVIDER:-sing-box}/$1/${BINARY_PROFILE}" in',
    ...cases,
    '        *) fail "unsupported release provider/platform/profile selection" ;;',
    '    esac',
    '}',
    '# END GENERATED CORE PROVIDER RELEASE POLICY',
    '',
  ].join('\n')
}

export async function withArtifactInspector(inspector, observe) {
  if (inspector) return observe(path.resolve(inspector))
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'solovey-release-inspector-'))
  try {
    const executable = path.join(scratch, `solovey-artifact-info${process.platform === 'win32' ? '.exe' : ''}`)
    execFileSync('go', ['build', '-mod=readonly', '-modfile=go.mod', '-trimpath', '-o', executable, './cmd/solovey-artifact-info'], {
      cwd: root, windowsHide: true, stdio: 'pipe', timeout: 300000,
      env: { ...process.env, GOFLAGS: '', GOWORK: 'off', GOOS: process.platform === 'win32' ? 'windows' : process.platform,
        GOARCH: ({ x64: 'amd64', ia32: '386' })[process.arch] ?? process.arch, CGO_ENABLED: '0' },
    })
    return await observe(executable)
  } finally {
    const actual = fs.realpathSync(scratch)
    assert.equal(path.dirname(actual), fs.realpathSync(os.tmpdir()))
    assert.ok(path.basename(actual).startsWith('solovey-release-inspector-'))
    fs.rmSync(actual, { recursive: true, force: true })
  }
}

export function inspectPanelArchive(inspector, file, target, identity) {
  const source = resolveProviderSource({ provider: target.provider }).source
  let observation
  try {
    observation = JSON.parse(execFileSync(inspector, ['--archive', path.resolve(file)], {
      input: JSON.stringify(source), encoding: 'utf8', windowsHide: true, timeout: 120000, maxBuffer: 256 << 10,
    }))
  } catch {
    throw Error('Panel package static source inspection failed')
  }
  assert.equal(observation.schema, 'solovey.panel-archive-observation/v1', 'Invalid package observation')
  assert.equal(observation.contentDigest, identity.sha256, 'Observed package digest differs')
  assert.equal(observation.size, identity.size, 'Observed package size differs')
  assert.deepEqual(observation.build?.coreProvider, source, 'Observed package provider source differs')
  assert.equal(observation.build.platform, target.platform, 'Observed package platform differs')
  assert.equal(observation.build.arch, target.arch, 'Observed package architecture differs')
  assert.equal(observation.build.binaryProfile, target.profile, 'Observed package profile differs')
  return observation
}

export function canonicalReleaseManifest(inspector, manifest) {
  try {
    return execFileSync(inspector, ['--canonical-manifest'], {
      input: JSON.stringify(manifest), windowsHide: true, timeout: 10000, maxBuffer: 2 << 20,
    })
  } catch {
    throw Error('Release manifest differs from the canonical runtime contract')
  }
}

export function verifyReleaseEnvelope(inspector, file, { trustRoots, now, channel }) {
  try {
    const observed = JSON.parse(execFileSync(inspector, ['--verify-release', path.resolve(file)], {
      input: JSON.stringify({ trustRoots, now: Math.floor(now), channel }),
      encoding: 'utf8', windowsHide: true, timeout: 10000, maxBuffer: 2 << 20,
    }))
    assert.equal(observed.schema, 'solovey.release-observation/v1')
    assert.match(observed.digest, /^[a-f0-9]{64}$/)
    return observed
  } catch {
    throw Error('Release envelope differs from the authenticated runtime contract')
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [command, ...args] = process.argv.slice(2)
    if (command === 'matrix' && args.length === 0) console.log(JSON.stringify({ include: linuxBuildTargets() }))
    else if (command === 'installer-policy' && args.length === 0) process.stdout.write(installerProviderPolicy())
    else if (command === 'artifact-name' && args.length === 3) {
      const [provider, platform, profile] = args
      const target = linuxPanelArtifacts().find(item => item.provider === provider && `linux-${item.arch}` === platform && item.profile === profile)
      if (!target) throw Error('Unsupported release provider/platform/profile selection')
      console.log(target.name)
    } else throw Error('usage: release-providers.mjs <matrix|installer-policy|artifact-name PROVIDER linux-ARCH PROFILE>')
  } catch (error) { console.error(error.message); process.exitCode = 1 }
}

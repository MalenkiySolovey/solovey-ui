#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const args = process.argv.slice(2)

function readArg(name, fallback = '') {
  const inline = args.find((arg) => arg.startsWith(`${name}=`))
  if (inline) return inline.slice(name.length + 1)
  const index = args.indexOf(name)
  if (index >= 0 && index + 1 < args.length) {
    const value = args[index + 1]
    // A flag token here means the value was omitted (PowerShell drops
    // empty-string arguments); fall back instead of consuming the flag.
    if (!value.startsWith('--')) return value
  }
  return fallback
}

function hasFlag(name) {
  return args.includes(name)
}

function fail(message) {
  console.error(message)
  process.exit(1)
}

const componentsDir = path.resolve(repoRoot, readArg('--components-dir', 'components'))
const outputPath = path.resolve(repoRoot, readArg('--out', 'app/components_generated.go'))
const commandOutputPath = path.resolve(repoRoot, readArg('--cmd-out', 'cmd/optional_commands_generated.go'))
const brokerOutputPath = path.resolve(repoRoot, readArg('--broker-out', 'cmd/solovey-privileged-broker/components_generated.go'))
const modulePath = readArg('--module', 'github.com/MalenkiySolovey/solovey-ui')
const profile = (readArg('--profile', process.env.SOLOVEY_UI_PROFILE || 'full') || 'full').toLowerCase()
const selectedArg = readArg('--selected-ids', process.env.SOLOVEY_UI_COMPONENT_IDS || '')

if (!fs.existsSync(componentsDir)) {
  fail(`components directory not found: ${componentsDir}`)
}

function readManifests() {
  return fs.readdirSync(componentsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const manifestPath = path.join(componentsDir, entry.name, 'component.json')
      if (!fs.existsSync(manifestPath)) return null

      let manifest
      try {
        manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
      } catch (error) {
        fail(`invalid component manifest ${manifestPath}: ${error.message}`)
      }

      if (!manifest?.id) fail(`component manifest ${manifestPath} is missing id`)
      return {
        id: String(manifest.id),
        dirName: entry.name,
        delivery: String(manifest.delivery || 'in-process'),
        cliEntries: readStringArray(manifest.cli?.entries ?? [], `component ${manifest.id} cli.entries`),
        brokerEntries: readStringArray(manifest.privilegedBroker?.entries ?? [], `component ${manifest.id} privilegedBroker.entries`),
      }
    })
    .filter(Boolean)
    .sort((left, right) => left.id.localeCompare(right.id))
}

const manifests = readManifests()
const manifestByID = new Map(manifests.map((manifest) => [manifest.id, manifest]))

const selectedIDs = selectedArg
  .split(',')
  .map((id) => id.trim())
  .filter(Boolean)

for (const id of selectedIDs) {
  if (!manifestByID.has(id)) {
    fail(`unknown component id in --selected-ids: ${id}`)
  }
}

const selected = profile === 'core' || profile === 'minimal'
  ? []
  : selectedIDs.length > 0
    ? selectedIDs.map((id) => manifestByID.get(id))
    : manifests

const imports = selected
  .filter((manifest) => manifest.delivery === 'in-process')
  .map((manifest) => `\t_ "${modulePath}/components/${manifest.dirName}"`)

const commandImports = selected
  .flatMap((manifest) =>
    manifest.cliEntries.map((entry) => `\t_ "${modulePath}/components/${manifest.dirName}/${entry}"`),
  )

const brokerImports = selected
  .flatMap((manifest) =>
    manifest.brokerEntries.map((entry) => `\t_ "${modulePath}/components/${manifest.dirName}/${entry}"`),
  )

const importBlock = imports.length > 0
  ? `import (\n${imports.join('\n')}\n)\n\n`
  : ''

const generated = `// Code generated by scripts/generate-component-imports.mjs; DO NOT EDIT.\n` +
  `//go:build !minimal\n\n` +
  `package app\n\n` +
  importBlock +
  `const soloveyGeneratedComponentImports = true\n`

if (!hasFlag('--dry-run')) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true })
  fs.writeFileSync(outputPath, generated)
  fs.mkdirSync(path.dirname(commandOutputPath), { recursive: true })
  fs.writeFileSync(commandOutputPath, generateCommandImports(commandImports))
  fs.mkdirSync(path.dirname(brokerOutputPath), { recursive: true })
  fs.writeFileSync(brokerOutputPath, generateBrokerImports(brokerImports))
}

console.log(`generated ${path.relative(repoRoot, outputPath).replaceAll(path.sep, '/')} with ${imports.length} in-process component import(s)`)
console.log(`generated ${path.relative(repoRoot, commandOutputPath).replaceAll(path.sep, '/')} with ${commandImports.length} optional command import(s)`)
console.log(`generated ${path.relative(repoRoot, brokerOutputPath).replaceAll(path.sep, '/')} with ${brokerImports.length} privileged broker import(s)`)

function readStringArray(value, label) {
  if (!Array.isArray(value)) {
    fail(`${label} must be an array`)
  }
  for (const item of value) {
    if (typeof item !== 'string' || !/^[A-Za-z0-9_./-]+$/.test(item) || item.includes('..')) {
      fail(`${label} contains invalid entry: ${item}`)
    }
  }
  return value
}

function generateCommandImports(commandImports) {
  const importBlock = commandImports.length > 0
    ? `import (\n${commandImports.join('\n')}\n)\n\n`
    : ''

  return `// Code generated by scripts/generate-component-imports.mjs; DO NOT EDIT.\n` +
    `//go:build !minimal\n\n` +
    `package cmd\n\n` +
    importBlock +
    `const soloveyGeneratedOptionalCommandImports = true\n`
}

function generateBrokerImports(brokerImports) {
  const importBlock = brokerImports.length > 0
    ? `import (\n${brokerImports.join('\n')}\n)\n\n`
    : ''

  return `// Code generated by scripts/generate-component-imports.mjs; DO NOT EDIT.\n` +
    `//go:build !minimal\n\n` +
    `package main\n\n` +
    importBlock +
    `const soloveyGeneratedPrivilegedBrokerImports = true\n`
}

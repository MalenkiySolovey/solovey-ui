#!/usr/bin/env node
// Generate the deployment-local typed projection from the canonical reference
// lock and its pinned fstools recipe. No upstream code is transferred.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import assert from 'node:assert/strict'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const workspace = path.resolve(root, '../..')
const lock = fs.readFileSync(path.join(workspace, 'upstreams/OPENWRT_REFERENCE_LOCK.md'), 'utf8')
function reference(id) {
  const section = lock.split(`#### ${id}. `)[1]?.split('\n#### ')[0]
  assert.ok(section, `missing canonical reference ${id}`)
  return {
    directory: section.match(/\*\*Directory\*\*: `([^`]+)`/)[1],
    revision: section.match(/\*\*HEAD SHA\*\*: `([0-9a-f]{40})`/)[1],
    ref: section.match(/\*\*Requested Ref\*\*: `([^`]+)`/)[1],
  }
}
const platform = reference('A1')
const fstools = reference('A2')
for (const source of [platform, fstools]) {
  const directory = path.join(workspace, source.directory)
  assert.equal(execFileSync('git', ['-c', `safe.directory=${directory}`, '-C', directory, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(), source.revision)
}
const recipe = fs.readFileSync(path.join(workspace, platform.directory, 'package/system/fstools/Makefile'), 'utf8')
assert.equal(recipe.match(/^PKG_SOURCE_VERSION:=(\w+)$/m)[1], fstools.revision)
const release = platform.ref.replace(/^v/, '')
const profiles = fs.readFileSync(path.join(root, 'scripts/openwrt-target-profile.sh'), 'utf8')
for (const match of profiles.matchAll(/OPENWRT_SOURCE_COMMIT='([^']+)'/g)) assert.equal(match[1], platform.revision)
for (const match of profiles.matchAll(/OPENWRT_RELEASE='([^']+)'/g)) assert.equal(match[1], release)
const output = `// Code generated by scripts/openwrt-persistence-authority.mjs; DO NOT EDIT.
// Source: workspace upstreams/OPENWRT_REFERENCE_LOCK.md A1/A2 and pinned fstools recipe.
package openwrt

func selectedPersistenceAuthority() PersistenceAuthority {
\treturn PersistenceAuthority{
\t\tOpenWrtRelease: ${JSON.stringify(release)},
\t\tOpenWrtSource:  ${JSON.stringify(platform.revision)},
\t\tFSToolsSource:  ${JSON.stringify(fstools.revision)},
\t}
}
`
const destination = path.join(root, 'deploy/openwrt/persistence_authority_generated.go')
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(destination, 'utf8').replaceAll('\r\n', '\n'), output, 'persistence authority projection drifted; regenerate from canonical lock')
else fs.writeFileSync(destination, output)
console.log('[openwrt-persistence-authority] canonical lock, recipe, release profiles and typed projection agree')

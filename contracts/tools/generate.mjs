import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import {createHash} from 'node:crypto'
import {execFileSync} from 'node:child_process'

const root = fileURLToPath(new URL('../management/v1/',import.meta.url))
const check = process.argv.includes('--check')
if(process.argv.slice(2).some(arg=>arg!=='--check')) throw Error('Only --check is supported')
const read = name => fs.readFileSync(path.join(root,name),'utf8').replaceAll('\r\n','\n')
const digest = value => createHash('sha256').update(value).digest('hex')
const schemaText = read('schema.json'), schema=JSON.parse(schemaText)
const keywords=new Set(['$schema','$id','$defs','$ref','title','description','type','enum','const','properties','required',
  'additionalProperties','oneOf','items','minLength','maxLength','pattern','minimum','maximum','minItems','maxItems','maxProperties'])
function audit(node) {
  for(const key of Object.keys(node)) if(!keywords.has(key)&&!key.startsWith('x-')) throw Error(`Unsupported schema assertion: ${key}`)
  if(node.$ref&&!schema.$defs[node.$ref.replace('#/$defs/','')]) throw Error(`Unknown reference ${node.$ref}`)
  if(node.type&&!['string','boolean','integer','object','array'].includes(node.type)) throw Error(`Unsupported type ${node.type}`)
  if('additionalProperties' in node&&typeof node.additionalProperties!=='boolean')throw Error('Only boolean additionalProperties is supported')
  if(node.enum&&node.enum.some(value=>typeof value!=='string'))throw Error('Only string enums are supported')
  if('const' in node&&typeof node.const!=='string')throw Error('Only string constants are supported')
  if(node.pattern) new RegExp(node.pattern)
  for(const child of Object.values(node.properties??{}))audit(child)
  for(const child of node.oneOf??[])audit(child)
  if(node.items)audit(node.items)
}
for(const definition of Object.values(schema.$defs))audit(definition)
function goName(key) {
  return key.replace(/(^|[-_])([a-z])/g,(_,a,b)=>b.toUpperCase()).replace(/Id(?=$|[A-Z])/g,'ID').replace(/Ttl$/,'TTL')
}
function goType(field) {
  if(field.$ref)return field.$ref.split('/').at(-1)
  if(field.oneOf)return 'json.RawMessage'
  if(field.type==='array')return `[]${goType(field.items)}`
  return {string:'string',boolean:'bool',integer:'int64'}[field.type]??'json.RawMessage'
}
let types='// Code generated by solovey-schema-go/v1. DO NOT EDIT.\n\npackage managementv1\n\nimport "encoding/json"\n\n'
for(const [name,node] of Object.entries(schema.$defs).sort(([a],[b])=>a<b?-1:1)) {
  if(node.type!=='object'){types+=`type ${name} ${goType(node)}\n\n`;continue}
  types+=`type ${name} struct {\n`
  for(const [key,field] of Object.entries(node.properties)) {
    const required=node.required.includes(key), base=goType(field)
    const type=required||base.startsWith('[]')||base==='json.RawMessage'?base:`*${base}`
    types+=`\t${goName(key)} ${type} \`json:"${key}${required?'':',omitempty'}"\`\n`
  }
  types+='}\n\n'
}
const goRoot=execFileSync('go',['env','GOROOT'],{encoding:'utf8'}).trim()
const goVersion=execFileSync('go',['env','GOVERSION'],{encoding:'utf8'}).trim()
types=execFileSync(path.join(goRoot,'bin',process.platform==='win32'?'gofmt.exe':'gofmt'),[],{input:types,encoding:'utf8'}).replaceAll('\r\n','\n')
function output(name,content) {
  if(check){if(!fs.existsSync(path.join(root,name))||read(name)!==content)throw Error(`Contract drift: ${name}`)}
  else fs.writeFileSync(path.join(root,name),content)
}
output('types.gen.go',types)
const vectorsText=read('vectors.json'),vectors=JSON.parse(vectorsText)
if(vectors.version!=='solovey.management.conformance/v1')throw Error('Unknown vector major')
const ids=new Set()
for(const vector of vectors.cases){if(!vector.id||ids.has(vector.id))throw Error('Missing/duplicate vector ID');ids.add(vector.id)}
const files={}
for(const name of ['README.md','codec.go','codec_test.go','schema.json','types.gen.go','vectors.json']) files[name]=digest(name==='types.gen.go'?types:read(name))
const generator=fs.readFileSync(fileURLToPath(import.meta.url),'utf8').replaceAll('\r\n','\n')
const manifest={contractVersion:schema['x-contractVersion'],schemaSHA256:digest(schemaText),
  generatedSHA256:digest(types),vectorsVersion:vectors.version,vectorsSHA256:digest(vectorsText),
  generator:{id:'solovey-schema-go/v1',sha256:digest(generator),gofmt:goVersion},files,
  bundleSHA256:digest(Object.entries(files).sort(([a],[b])=>a<b?-1:1).map(([name,hash])=>`${name}\0${hash}\n`).join(''))}
output('manifest.json',JSON.stringify(manifest,null,2)+'\n')
console.log(JSON.stringify({mode:check?'check':'generate',...manifest,files:undefined}))
